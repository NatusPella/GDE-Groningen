#!/usr/bin/env python3
"""Write game/js/ringroute.js: one lap of the full ringweg for the ring race.

The loop comes from ringloop.route_loop over game/citymap.json (one-way
carriageways respected), resampled to ~STEP m. Checkpoints are centreline
points ~CP_SPACING m apart whose connecting straight lines clear every
building footprint, so the guidance line never cuts through a block.
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ringloop import route_loop  # noqa: E402

MAP_PATH = "game/citymap.json"
DST = "game/js/ringroute.js"
START = (430, 1633)   # Zuidelijke Ringweg westbound, at street level before Julianaplein
STEP = 20.0
CP_SPACING = 600.0
CP_MIN = 250.0


def resample(loop, step):
    pts = loop + [loop[0]]
    out = []
    carry = 0.0
    for a, b in zip(pts, pts[1:]):
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        if L < 1e-6:
            continue
        n = max(1, int(round(L / step)))
        for i in range(n):
            t = i / n
            out.append([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2]])
    return out


def point_in_poly(x, y, pts):
    inside = False
    j = len(pts) - 1
    for i in range(len(pts)):
        xi, yi = pts[i]
        xj, yj = pts[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def main():
    with open(MAP_PATH) as f:
        data = json.load(f)
    loop = route_loop(data["roads"])
    route = resample(loop, STEP)
    k0 = min(range(len(route)), key=lambda i: math.hypot(route[i][0] - START[0], route[i][1] - START[1]))
    route = route[k0:] + route[:k0]
    n = len(route)
    s = [0.0]
    for i in range(1, n):
        s.append(s[-1] + math.hypot(route[i][0] - route[i - 1][0], route[i][1] - route[i - 1][1]))
    L = s[-1] + math.hypot(route[0][0] - route[-1][0], route[0][1] - route[-1][1])

    G = 50.0
    grid = {}
    for b in data["buildings"]:
        xs, ys = [p[0] for p in b["pts"]], [p[1] for p in b["pts"]]
        bb = (min(xs), min(ys), max(xs), max(ys))
        for gx in range(int(bb[0] // G), int(bb[2] // G) + 1):
            for gy in range(int(bb[1] // G), int(bb[3] // G) + 1):
                grid.setdefault((gx, gy), []).append((bb, b["pts"]))

    def clear(i, j):
        ax, ay, bx, by = route[i][0], route[i][1], route[j][0], route[j][1]
        m = max(1, int(math.hypot(bx - ax, by - ay) / 4))
        for k in range(m + 1):
            x, y = ax + (bx - ax) * k / m, ay + (by - ay) * k / m
            for bb, pts in grid.get((int(x // G), int(y // G)), []):
                if bb[0] <= x <= bb[2] and bb[1] <= y <= bb[3] and point_in_poly(x, y, pts):
                    return False
        return True

    cps = [0]
    i = 0
    while True:
        target = s[cps[-1]] + CP_SPACING
        if target > L - CP_MIN:
            break
        j = min(range(cps[-1] + 1, n), key=lambda q: abs(s[q] - target))
        while j > cps[-1] + 1 and s[j] - s[cps[-1]] > CP_MIN and not clear(cps[-1], j):
            j -= 1
        if not clear(cps[-1], j):
            j = cps[-1] + 1
            while j < n - 1 and not clear(cps[-1], j + 1):
                j += 1
        cps.append(j)
        if j >= n - 2:
            break
    # the closing leg must clear too
    while len(cps) > 2 and not clear(cps[-1], 0):
        cps.pop()

    rows = []
    for k in range(0, n, 8):
        rows.append("  " + " ".join(f"[{p[0]:.1f},{p[1]:.1f},{p[2]:.1f}]," for p in route[k:k + 8]))
    with open(DST, "w") as f:
        f.write(f"""// Generated by scripts/gen_ringroute.py from citymap.json - do not edit.
// One lap of the full Groningen ringweg ({L / 1000:.1f} km), clockwise on the
// map: Zuidelijke Ringweg westbound -> Julianaplein -> Vrijheidsplein ->
// Westelijke Ringweg north -> Friesestraatweg -> Noordelijke Ringweg
// (Plataanlaan, Noordzeeweg) -> Oostelijke Ringweg (Beneluxweg) south ->
// Euvelgunne -> Beneluxweg west -> Europaplein -> Zuidelijke Ringweg, over
// the real viaducts and through the sunken sections. Drivable centrelines
// (one-way respected), each entry [x, y, halfWidth].
export const RING_ROUTE = [
{chr(10).join(rows)}
];

// Indices into RING_ROUTE: every checkpoint is a centreline point and the
// straight line between consecutive ones clears every building footprint.
// Index 0 is the start/finish line.
export const RING_CHECKPOINTS = {json.dumps(cps, separators=(', ', ':'))};

export const RING_LENGTH = {round(L)};
""")
    print(f"ring route: {n} points, {L:.0f} m, {len(cps)} checkpoints -> {DST}")


if __name__ == "__main__":
    main()
