// Generates game/js/inputglyphs_data.js from the Kenney map files in game/fonts/input (CC0).
// node scripts/input_glyph_map.mjs [--check]; --check fails when the data file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'game', 'fonts', 'input');
const OUT = path.join(ROOT, 'game', 'js', 'inputglyphs_data.js');
const SETS = ['keys', 'xbox', 'ps', 'deck', 'generic', 'touch'];

function parse(file) {
  const t = {};
  for (const l of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^([a-z0-9_]+):\s*U\+([0-9A-F]+)/i.exec(l.trim());
    if (m) t[m[1]] = parseInt(m[2], 16);
  }
  return t;
}
const data = {};
for (const set of SETS) data[set] = parse(path.join(DIR, `input-${set}-map.txt`));
// The glyphs live in the private use area: store the code points as numbers, so the file stays plain ASCII.
const src = `// Generated by scripts/input_glyph_map.mjs from the Kenney Input Prompts font maps (CC0). Do not edit by hand.\n// Values are code points in the private use area of the matching input-<set>.ttf (game/fonts/input).\nexport const INPUT_GLYPHS = ${JSON.stringify(data, null, 1)};\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== src) { console.error('inputglyphs_data.js is out of date: node scripts/input_glyph_map.mjs'); process.exit(1); }
  console.log('inputglyphs_data.js is up to date');
} else {
  fs.writeFileSync(OUT, src);
  console.log('written', path.relative(ROOT, OUT), SETS.map((k) => `${k}:${Object.keys(data[k]).length}`).join(' '));
}
