// Generates the two Steam files that follow the game's own data (#64):
//   steam/steam_input/game_actions_APP_ID.vdf   the Steam Input action sets, one per controller
//                                                situation (controls.js PAD_MAPS), with Dutch names
//   steam/achievements.json                      every prestatie id with an empty Steam API name
// Local only: nothing here contacts Steam. Run it again after the controls or the
// prestaties change; scripts/steam_test.mjs fails when the files are out of date.
//   node steam/make-steam-files.mjs          write the files
//   node steam/make-steam-files.mjs --check  only compare (exit 1 when out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAD_MAPS } from '../game/js/controls.js';
import { labelFor } from '../game/js/touchlogic.js';
import { ACHIEVEMENTS } from '../game/js/achievements.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));

// the situations of PAD_MAPS and what a player calls them (neutral Dutch, no brands)
export const SET_TITLES = {
  foot: 'Lopen', vehicle: 'Rijden', vehicleManual: 'Rijden met versnellingen', skutsje: 'Zeilen', heli: 'Helikopter',
  pigeon: 'Duif', train: 'Trein', minigame: 'Minigame', klokken: 'Beiaard', pannenkoek: 'Pannenkoekenschip',
  foodtruck: 'Frituurwagen', menu: 'Menu',
};
// the controller's slots in the order a configurator lists them
const SLOTS = ['a', 'b', 'x', 'y', 'lb', 'rb', 'lt', 'rt', 'ls', 'rs', 'up', 'down', 'left', 'right', 'view', 'start'];
// slots in the buttons' own words: nothing here names a maker's layout
const SLOT_WORDS = { a: 'onder', b: 'rechts', x: 'links', y: 'boven', lb: 'linker schouder', rb: 'rechter schouder', lt: 'linker trekker', rt: 'rechter trekker', ls: 'linker stick indrukken', rs: 'rechter stick indrukken', up: 'kruis omhoog', down: 'kruis omlaag', left: 'kruis links', right: 'kruis rechts', view: 'kaartknop', start: 'pauzeknop' };

const tabs = (n) => '\t'.repeat(n);
const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');

export function actionSets() {
  const sets = [];
  for (const [ctx, title] of Object.entries(SET_TITLES)) {
    const map = PAD_MAPS[ctx];
    if (!map) continue;
    const buttons = [];
    for (const slot of SLOTS) {
      const action = map[slot];
      if (action == null) continue;
      const label = labelFor(ctx, action) || (slot === 'start' ? 'Pauze' : slot === 'view' ? 'Kaart' : '');
      if (!label) continue;
      buttons.push({ name: `${ctx}_${slot}`, label: `${label} (${SLOT_WORDS[slot]})` });
    }
    sets.push({ ctx, title, buttons });
  }
  return sets;
}

export function inputVdf() {
  const sets = actionSets();
  const L = [];
  L.push('// Steam Input: the action sets of GDE Groningen, one per situation. Generated by');
  L.push('// steam/make-steam-files.mjs from game/js/controls.js; do not edit by hand.');
  L.push('// Rename this file to game_actions_<app id>.vdf and upload it in Steamworks');
  L.push('// (Steam Input > Steam Input Configurator Settings). The game also works with the');
  L.push('// standard "Gamepad" template: it reads the controller itself (gamepad.js).');
  L.push('"In Game Actions"', '{', `${tabs(1)}"actions"`, `${tabs(1)}{`);
  for (const s of sets) {
    L.push(`${tabs(2)}"${s.ctx}"`, `${tabs(2)}{`);
    L.push(`${tabs(3)}"title"\t"#Set_${s.ctx}"`);
    L.push(`${tabs(3)}"StickPadGyro"`, `${tabs(3)}{`);
    L.push(`${tabs(4)}"beweeg_${s.ctx}"`, `${tabs(4)}{`, `${tabs(5)}"title"\t"#Act_beweeg_${s.ctx}"`, `${tabs(5)}"input_mode"\t"joystick_move"`, `${tabs(4)}}`);
    L.push(`${tabs(4)}"kijk_${s.ctx}"`, `${tabs(4)}{`, `${tabs(5)}"title"\t"#Act_kijk_${s.ctx}"`, `${tabs(5)}"input_mode"\t"joystick_camera"`, `${tabs(4)}}`);
    L.push(`${tabs(3)}}`);
    L.push(`${tabs(3)}"Button"`, `${tabs(3)}{`);
    for (const b of s.buttons) L.push(`${tabs(4)}"${b.name}"\t"#Act_${b.name}"`);
    L.push(`${tabs(3)}}`, `${tabs(2)}}`);
  }
  L.push(`${tabs(1)}}`);
  // Steamworks wants an "english" block; the game is Dutch only, so both blocks hold the same Dutch text
  const strings = [];
  for (const s of sets) {
    strings.push([`Set_${s.ctx}`, s.title], [`Act_beweeg_${s.ctx}`, 'Bewegen'], [`Act_kijk_${s.ctx}`, 'Kijken']);
    for (const b of s.buttons) strings.push([`Act_${b.name}`, b.label]);
  }
  L.push(`${tabs(1)}"localization"`, `${tabs(1)}{`);
  for (const lang of ['english', 'dutch']) {
    L.push(`${tabs(2)}"${lang}"`, `${tabs(2)}{`);
    for (const [k, v] of strings) L.push(`${tabs(3)}"${k}"\t"${esc(v)}"`);
    L.push(`${tabs(2)}}`);
  }
  L.push(`${tabs(1)}}`, '}', '');
  return L.join('\n');
}

export function achievementsJson() {
  const rows = ACHIEVEMENTS.map((a) => ({ id: a.id, titel: a.title, omschrijving: a.desc, verborgen: !!a.hidden, steamApiNaam: '' }));
  return JSON.stringify({
    _uitleg: 'Prestatie-ID van het spel naar de API-naam in Steamworks (Stats & Achievements). Leeg tot er een app-id is; vul steamApiNaam in zoals je hem in Steamworks aanmaakt (hoofdletters, cijfers en _, tot 128 tekens). Gegenereerd door steam/make-steam-files.mjs.',
    prestaties: rows,
  }, null, 2) + '\n';
}

export const FILES = () => [
  [path.join(HERE, 'steam_input', 'game_actions_APP_ID.vdf'), inputVdf()],
  [path.join(HERE, 'achievements.json'), achievementsJson()],
];

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, text] of FILES()) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (check) {
      if (have !== text) { stale++; console.log('verouderd:', path.relative(process.cwd(), file)); }
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text, 'utf8');
    console.log('geschreven:', path.relative(process.cwd(), file), `(${text.length} tekens)`);
  }
  if (check) { console.log(stale ? `${stale} verouderd` : 'bestanden zijn actueel'); process.exit(stale ? 1 : 0); }
}
